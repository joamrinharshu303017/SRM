def extract_docx(file_path):

    document = Document(file_path)

    blocks = []
    markdown = []

    for paragraph in document.paragraphs:

        text = paragraph.text.strip()

        if not text:
            continue

        style = paragraph.style.name.lower()

        if "heading" in style:
            block_type = "heading"
            markdown.append("## " + text)
        else:
            block_type = "paragraph"
            markdown.append(text)

        blocks.append({
            "type": block_type,
            "text": text,
            "page": None,
            "bbox": None,
            "confidence": 0.95,
            "source": "docx"
        })

    # Extract tables
    for table_number, table in enumerate(
        document.tables,
        start=1
    ):

        rows = []

        for row in table.rows:

            rows.append([
                cell.text.strip()
                for cell in row.cells
            ])

        blocks.append({
            "type": "table",
            "table_id": table_number,
            "rows": rows,
            "page": None,
            "bbox": None,
            "confidence": 0.95,
            "source": "docx_table"
        })

        markdown.append(
            f"\n### Table {table_number}\n"
        )

        for row in rows:
            markdown.append(
                "| " + " | ".join(row) + " |"
            )

    return blocks, "\n\n".join(markdown)



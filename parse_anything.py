def extract_txt(file_path):

    with open(file_path, "r", encoding="utf-8", errors="replace") as f:
        text = f.read()

    blocks = []

    for line_number, line in enumerate(text.splitlines(), start=1):

        line = line.strip()

        if not line:
            continue

        blocks.append({
            "type": "text",
            "text": line,
            "page": 1,
            "line": line_number,
            "bbox": None,
            "confidence": 1.0,
            "source": "text_file"
        })

    return blocks, text



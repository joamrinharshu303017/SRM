def process_file(file_path):

    if file_path is None:
        return (
            "",
            "{}",
            "⚠️ Please upload a document."
        )

    try:

        blocks, markdown = parse_document(
            file_path
        )

        blocks = add_confidence_status(
            blocks
        )

        result = create_json(
            blocks,
            file_path
        )

        json_output = json.dumps(
            result,
            indent=2,
            ensure_ascii=False
        )

        confidence = calculate_confidence(
            blocks
        )

        low_confidence = sum(
            1
            for block in blocks
            if block.get("status")
            == "LOW_CONFIDENCE"
        )

        statistics = f"""
## 📊 Parsing Results

**File:** `{Path(file_path).name}`

**Format:** `{Path(file_path).suffix.lower()}`

**Total Blocks:** `{len(blocks)}`

**Average Confidence:** `{confidence}%`

**Low Confidence Blocks:** `{low_confidence}`

### Pipeline

`Detect → Extract → Assemble → Verify`
"""

        return (
            markdown,
            json_output,
            statistics
        )

    except Exception as error:

        error_result = {
            "success": False,
            "error_code": "PARSING_FAILED",
            "message": str(error)
        }

        return (
            "",
            json.dumps(
                error_result,
                indent=2
            ),
            f"❌ Error: {str(error)}"
        )



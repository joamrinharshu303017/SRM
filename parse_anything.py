def extract_image(file_path):

    image = Image.open(file_path).convert("RGB")

    data = pytesseract.image_to_data(
        image,
        output_type=pytesseract.Output.DICT
    )

    blocks = []
    words = []

    for i, word in enumerate(data["text"]):

        word = word.strip()

        if not word:
            continue

        try:
            confidence = float(data["conf"][i])
        except:
            confidence = 0

        if confidence < 0:
            confidence = 0

        x = int(data["left"][i])
        y = int(data["top"][i])
        w = int(data["width"][i])
        h = int(data["height"][i])

        words.append(word)

        blocks.append({
            "type": "ocr_text",
            "text": word,
            "page": 1,
            "bbox": [x, y, x + w, y + h],
            "confidence": round(confidence / 100, 3),
            "source": "tesseract_ocr"
        })

    return blocks, " ".join(words)



def calculate_confidence(blocks):

    scores = []

    for block in blocks:

        value = block.get("confidence")

        if isinstance(value, (int, float)):
            scores.append(value)

    if not scores:
        return 0.0

    return round(
        sum(scores) / len(scores) * 100,
        2
    )


def add_confidence_status(blocks):

    for block in blocks:

        confidence = block.get(
            "confidence",
            0
        )

        if confidence < 0.60:

            block["status"] = "LOW_CONFIDENCE"

            block["warning"] = (
                "Manual verification recommended"
            )

        elif confidence < 0.80:

            block["status"] = "REVIEW"

        else:

            block["status"] = "HIGH_CONFIDENCE"

    return blocks


def create_json(blocks, file_path):

    return {
        "project": "ParseAnything AI",
        "version": "1.0",
        "filename": Path(file_path).name,
        "format": Path(file_path).suffix.lower(),
        "total_blocks": len(blocks),
        "average_confidence": calculate_confidence(
            blocks
        ),
        "blocks": blocks
    }



def extract_xlsx(file_path):

    workbook = load_workbook(
        file_path,
        data_only=True
    )

    blocks = []
    markdown = []

    for sheet in workbook.worksheets:

        data = list(sheet.values)

        if not data:
            continue

        df = pd.DataFrame(data)

        clean_df = df.fillna("")

        rows = clean_df.values.tolist()

        blocks.append({
            "type": "table",
            "sheet": sheet.title,
            "rows": rows,
            "page": None,
            "bbox": None,
            "confidence": 0.99,
            "source": "excel"
        })

        markdown.append(
            f"## Sheet: {sheet.title}\n\n"
        )

        markdown.append(
            clean_df.to_markdown(
                index=False
            )
        )

    return blocks, "\n\n".join(markdown)


